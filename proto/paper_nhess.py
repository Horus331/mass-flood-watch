"""Build docs/proto/paper/MANUSCRIPT_NHESS.md from MANUSCRIPT.md (master) and REFERENCES.md: src comments and R numbers removed,
author-year citations with a comma (NHESS style), alphabetical reference list. Run after every edit of the master.
    python proto/paper_nhess.py"""
import os, re
D = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'docs/proto/paper')
s = open(f'{D}/MANUSCRIPT.md').read()
s = re.sub(r'\n?<!--.*?-->', '', s, flags=re.S)
s = re.sub(r',\s*R\d+\b', '', s); s = re.sub(r'\s*\(R\d+\)', '', s)
s = re.sub(r'(et al\.|\b[A-Z][\w\-]+ and [A-Z][\w\-]+)\s+((?:19|20)\d{2})(?=[;)])', r'\1, \2', s)
i = s.index('## References')
refs = open(f'{D}/REFERENCES.md').read()
items = re.findall(r'^\s*\d+b?\.\s+(.*?)(?=\n\s*\d+b?\.\s|\n\n|\Z)', refs, flags=re.S | re.M); out = []
for it in items:
    it = ' '.join(it.split()); it = re.sub(r'\s*[✓◐—]\s*', ' ', it)
    it = re.sub(r'\[R\d+\]|\[added[^\]]*\]|\(open copy:[^)]*\)|\(PubMed \d+\)', '', it); out.append(' '.join(it.split()))
head = s[:i].replace('# Paper 1 manuscript draft', '# Paper 1 manuscript (NHESS version; generated by proto/paper_nhess.py from MANUSCRIPT.md, do not edit)')
head = re.sub(r'Working title:.*?\n\n', '', head, count=1, flags=re.S); head = re.sub(r'Status:.*?\n\n', '', head, count=1, flags=re.S)
head = re.sub(r'## Abstract \(.*?\)', '## Abstract', head)
open(f'{D}/MANUSCRIPT_NHESS.md', 'w').write(head + '## References\n\n' + '\n\n'.join(sorted(out, key=str.lower)) + '\n')
print(len(out), 'references')
